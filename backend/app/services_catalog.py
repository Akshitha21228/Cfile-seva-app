GST_RATE = 0.18


def price_for(service_id: str) -> int:
    if service_id not in SERVICE_PRICES:
        raise ValueError(f"Unknown service id: {service_id}")
    return SERVICE_PRICES[service_id]


def compute_total(items: list[tuple[str, int]]) -> float:
    """items: list of (service_id, quantity) pairs, mirroring CartContext's subtotal/gst/total math."""
    subtotal = sum(price_for(sid) * qty for sid, qty in items)
    return round(subtotal * (1 + GST_RATE), 2)
